import hashlib, math, os, sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import ckpt_key
from fold_D import zeros380, inv_Nbar, D_cue_analytic, D_emp, TWO_PI
from fold_surrogate import Sect, surrogate_field, A, NZ


def _sha(name):
    return hashlib.sha256(
        open(os.path.join(HERE, name), "rb").read()).hexdigest()

DEPSX = {f: _sha(f) for f in ("fold_D.py", "fold_surrogate.py",
                              "crossing_probe.py")}
KEYFILE = os.path.join(HERE, "fold_surrogate.py")


def _zsha(a):
    return hashlib.sha256(
        np.ascontiguousarray(a).tobytes()).hexdigest()[:16]


C0 = 120.0
TAUS = [290.0, 300.0, 310.0, 320.0, 330.0, 340.0]
NDRAW = 200          # per ensemble per tau0
SEED0 = 24000        # deterministic ladder, disjoint from 1be's
KTHR = list(range(4, 13))   # exceedance thresholds 10^-4 .. 10^-12
MFLOOR = 1e-14       # numerical-zero classification


def profiles():
    SIXTH = 1.0/6.0
    MERTENS = 0.2614972128476428
    X0 = 320.0/TWO_PI
    Vsat = (math.log(math.log(X0)) + MERTENS + 1)/math.pi**2
    lags = np.arange(1, 1025).astype(float)
    Dz = np.minimum(D_cue_analytic(lags), Vsat) - SIXTH
    Dc = D_cue_analytic(lags) - SIXTH
    return Dz, Dc


def calibrate(Dz, Dc):
    scale = {}
    crng = np.random.default_rng(99)      # the 1be protocol verbatim
    for name, prof in (("zeta", Dz), ("cue", Dc)):
        r = np.mean([D_emp(surrogate_field(prof, crng), 48)
                     for _ in range(80)], axis=0)/prof[:48]
        scale[name] = 1.0/math.sqrt(float(np.mean(r)))
    return scale


def draw_config(prof, sc, rng, comb):
    d = sc*surrogate_field(prof, rng)
    return np.array([inv_Nbar(k - 0.5 + d[k-1], g0=comb[k-1])
                     for k in range(1, NZ + 1)])


def band_count(zeros, t0):
    W = C0/A
    return int(np.sum((zeros > t0 - W) & (zeros < t0 + W)))


def stats(ms):
    ms = np.asarray(ms)
    lg = np.log10(np.maximum(ms, MFLOOR))
    exc = {k: float(np.mean(ms < 10.0**(-k))) for k in KTHR}
    return {"n": len(ms),
            "deciles": [float(np.quantile(lg, q/10)) for q in range(11)],
            "median_log10": float(np.median(lg)),
            "frac_floor": float(np.mean(ms <= MFLOOR*1.01)),
            "exceedance": exc}


def run():
    Z = zeros380()
    comb = np.array([inv_Nbar(float(k)) for k in range(1, NZ + 1)])
    Dz, Dc = profiles()
    params = {"deps": DEPSX, "c": C0, "A": A, "taus": TAUS,
              "ndraw": NDRAW, "seed0": SEED0, "z_sha": _zsha(Z)}
    st = ckpt_key.load("crossing_null", KEYFILE, params)
    if st is None:
        scale = calibrate(Dz, Dc)
        print(f"calibration: zeta {scale['zeta']:.4f} "
              f"cue {scale['cue']:.4f}", flush=True)
        S = Sect(C0)
        Nsh = 2*C0/math.pi
        st = {"Nsh": Nsh, "scale": scale, "points": {}}
        for t0 in TAUS:
            pp = {"deps": DEPSX, "c": C0, "A": A, "t0": t0,
                  "ndraw": NDRAW, "seed0": SEED0, "z_sha": _zsha(Z)}
            pname = f"crossing_t{int(t0)}"
            cached = ckpt_key.load(pname, KEYFILE, pp)
            if cached is not None:
                st["points"][f"{t0:.0f}"] = cached
                print(f"tau0={t0:5.0f}: restored from save point",
                      flush=True)
                continue
            target = band_count(comb, t0)
            m_true = float(S.margin(Z, t0))
            nb_true = band_count(Z, t0)
            ens = {}
            # (a) zeta-profile, UNconditioned
            rng = np.random.default_rng(SEED0 + int(t0))
            ms, nbs = [], []
            for _ in range(NDRAW):
                g = draw_config(Dz, scale["zeta"], rng, comb)
                ms.append(float(S.margin(g, t0)))
                nbs.append(band_count(g, t0))
            ens["zeta_uncond"] = stats(ms)
            ens["zeta_uncond"]["counts"] = {
                "target": target, "mean": float(np.mean(nbs)),
                "sd": float(np.std(nbs)),
                "p_above": float(np.mean(np.array(nbs) > target))}
            raw = {"zeta_uncond": np.array(ms)}
            # (b)/(c) conditioned (the 1bc protocol)
            for name, prof in (("zeta_cond", Dz), ("cue_cond", Dc)):
                rng = np.random.default_rng(
                    SEED0 + 1000 + int(t0) + (0 if name[0] == "z" else 1))
                sc = scale["zeta" if name[0] == "z" else "cue"]
                ms, tried = [], 0
                while len(ms) < NDRAW and tried < 20*NDRAW:
                    tried += 1
                    g = draw_config(prof, sc, rng, comb)
                    if band_count(g, t0) != target:
                        continue
                    ms.append(float(S.margin(g, t0)))
                ens[name] = stats(ms)
                ens[name]["tried"] = tried
                raw[name] = np.array(ms)
            ens["true"] = {"m": m_true, "nb": nb_true,
                           "log10": float(math.log10(max(m_true, MFLOOR)))}
            # the zeros' percentile against each ensemble, from the
            # raw arrays
            for name, arr in raw.items():
                ens["true"][f"pct_vs_{name}"] = float(
                    np.mean(arr < m_true))
            ens["true"]["pct_vs_uncond"] = ens["true"][
                "pct_vs_zeta_uncond"]
            ckpt_key.save(pname, KEYFILE, pp, ens)
            st["points"][f"{t0:.0f}"] = ens
            print(f"tau0={t0:5.0f}: target nb {target} | true m "
                  f"{m_true:.3e} (nb {nb_true}, pct-vs-uncond "
                  f"{ens['true']['pct_vs_uncond']:.2f}) | "
                  f"uncond med {ens['zeta_uncond']['median_log10']:+.2f} "
                  f"floor-frac {ens['zeta_uncond']['frac_floor']:.2f} | "
                  f"zcond med {ens['zeta_cond']['median_log10']:+.2f} | "
                  f"cue med {ens['cue_cond']['median_log10']:+.2f}",
                  flush=True)
        ckpt_key.save("crossing_null", KEYFILE, params, st)
    else:
        for t0k, ens in st["points"].items():
            print(f"tau0={t0k}: true m {ens['true']['m']:.3e} "
                  f"pct-vs-uncond {ens['true']['pct_vs_uncond']:.2f} | "
                  f"uncond med {ens['zeta_uncond']['median_log10']:+.2f} "
                  f"| zcond {ens['zeta_cond']['median_log10']:+.2f} | "
                  f"cue {ens['cue_cond']['median_log10']:+.2f}",
                  flush=True)
    return st


if __name__ == "__main__":
    st = run()
    print("crossing probe complete", flush=True)
