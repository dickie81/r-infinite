def part_A():
    print("=" * 78)
    print("PART A: Lie algebra generated by J1, J2")
    print("=" * 78)
    for n in (6, 8, 10, 12):
        J1, J2 = pairing_J(n, 0), pairing_J(n, 1)
        basis = [J1, J2]
        rank = 2
        while True:
            new = []
            for A, B in combinations(basis, 2):
                new.append(A @ B - B @ A)
            cand = basis + new
            M = np.array([c.flatten() for c in cand])
            r = np.linalg.matrix_rank(M, tol=1e-9)
            if r == rank:
                break
            # keep an independent subset
            q, rr, piv = np.linalg.qr(M.T, mode='reduced'), None, None
            u, s, vt = np.linalg.svd(M, full_matrices=False)
            keep = [cand[i] for i in range(len(cand))]
            basis, rank = keep, r
            if len(basis) > 4 * n * n:
                break
        dim_so = n * (n - 1) // 2
        m = n // 2
        tag = ("= (n/2)^2 = dim u(n/2)" if rank == m * m else
               ("FULL so(n)" if rank == dim_so else "proper subalgebra"))
        print(f"  n = {n:2d}: closure dim = {rank:3d}   dim so(n) = {dim_so:3d}"
              f"   {tag}")
    # identify the algebra for n = 12: center of the closure
    n = 12
    J1, J2 = pairing_J(n, 0), pairing_J(n, 1)
    basis = [J1, J2]
    for _ in range(6):
        new = [A @ B - B @ A for A, B in combinations(basis, 2)]
        M = np.array([c.flatten() for c in basis + new])
        u, s, vt = np.linalg.svd(M, full_matrices=False)
        r = int((s > 1e-9 * s[0]).sum())
        basis = [vt[i].reshape(n, n) for i in range(r)]
        if len(basis) == r and r == (n // 2) ** 2:
            break
    # ideal decomposition via the adjoint Casimir: orthonormalise basis
    # under tr(A^T B), build structure constants, C = sum_i (ad B_i)^2;
    # by Schur C is a constant on each simple ideal -> eigenvalue
    # multiplicities = ideal dimensions.
    G = np.array([b.flatten() for b in basis])
    u3, s3, vt3 = np.linalg.svd(G, full_matrices=False)
    ob = [vt3[i].reshape(n, n) for i in range(len(basis))]
    r = len(ob)
    ad = np.zeros((r, r, r))
    Pn = np.array([b.flatten() for b in ob]).T
    for i in range(r):
        for j in range(r):
            br = (ob[i] @ ob[j] - ob[j] @ ob[i]).flatten()
            ad[i][:, j] = 0.0
            coeff, *_ = np.linalg.lstsq(Pn, br, rcond=None)
            ad[i][:, j] = coeff
    C = sum(ad[i] @ ad[i] for i in range(r))
    ev = np.sort(np.linalg.eigvalsh(C))
    groups = []
    for v in ev:
        if groups and abs(v - groups[-1][0]) < 1e-6 * max(1, abs(v)):
            groups[-1][1] += 1
            groups[-1][0] = v
        else:
            groups.append([v, 1])
    mult = sorted(g[1] for g in groups)
    cdim = sum(g[1] for g in groups if abs(g[0]) < 1e-8)
    print(f"  adjoint-Casimir block dimensions: {mult}"
          f"   (eigenvalues {[round(float(g[0]), 4) for g in groups]})")
    print(f"  center dim (Casimir kernel) = {cdim}   (u(m) predicts 1)")
    # the 1-dim block: reconstruct its element Z and test centrality
    w_ev, V = np.linalg.eigh(C)
    order = np.argsort(w_ev)
    # find index of the isolated eigenvalue
    iso = None
    for g in groups:
        if g[1] == 1:
            iso = g[0]
    idx = int(np.argmin(np.abs(w_ev - iso)))
    zc = V[:, idx]
    Z = sum(zc[i] * ob[i] for i in range(r))
    Z = Z / math.sqrt(abs(np.trace(Z @ Z)) / n)
    comm = max(np.linalg.norm(Z @ B - B @ Z) for B in ob)
    err = np.linalg.norm(Z @ Z + np.eye(n))
    print(f"  isolated block's element Z:  max ||[Z, basis]|| = {comm:.2e},"
          f"  ||Z^2 + I|| = {err:.2e}")
    if comm < 1e-6 and err < 1e-6:
        print("  => VERIFIED: the closure is u(n/2) = span(Z) + su(n/2), with")
        print("     Z an EMERGENT complex structure (Z^2 = -I) that commutes")
        print("     with everything the two pairings generate.  The pairing")
        print("     ambiguity is self-repairing: J1, J2 disagree about which")
        print("     axes are partners, but their composites close on the")
        print("     unitary algebra of a single canonical J.")
    else:
        print("  => 1-dim block is NOT central: algebra is semisimple of dim")
        print("     (n/2)^2 with the block structure printed above.")


