def part_B():
    print()
    print("=" * 78)
    print("PART B: displacement-phase triviality (the i-per-step rule)")
    print("=" * 78)
    d = np.arange(D_MIN, D_MAX + 1)
    n = len(d)
    w1 = np.array([1.0 / (2.0 * alpha(int(x))) for x in d[:-1]])
    w2 = np.array([N_lapse(int(x)) * N_lapse(int(x) + 1) for x in d[:-2]])
    H = np.zeros((n, n), dtype=complex)
    for j, w in enumerate(w1):                      # 1-step hops, phase i
        H[j + 1, j] = -w * 1j
        H[j, j + 1] = np.conj(H[j + 1, j])
        H[j, j] += w
        H[j + 1, j + 1] += w
    for j, w in enumerate(w2):                      # 2-step hops, phase i^2
        H[j + 2, j] = -w * (1j ** 2)
        H[j, j + 2] = np.conj(H[j + 2, j])
    U = np.diag([1j ** k for k in range(n)])
    Hg = U.conj().T @ H @ U
    print(f"  max |Im| of gauge-transformed operator: "
          f"{np.max(np.abs(Hg.imag)):.2e}")
    e1 = np.linalg.eigvalsh(H)
    e2 = np.linalg.eigvalsh(Hg.real)
    print(f"  max eigenvalue difference vs real form: "
          f"{np.max(np.abs(e1 - e2)):.2e}")
    print("  => i^(Delta d) phases are pure gauge on ANY graph: no composite")
    print("     of displacement-phased cascade hops can carry flux.  The")
    print("     cascade's imaginary unit has zero curvature.")


