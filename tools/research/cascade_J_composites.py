"""
Composites of the cascade's two complex structures.

Addendum 3 found: J-twists on the layer chain are gauge-trivial (path graph,
no loops), and the pairing-offset ambiguity gives two complex structures
J1, J2 whose composite T = J2 J1 is a signed two-step SHIFT along the axis
chain.  This script investigates the composites systematically.

  A. Algebra: what Lie algebra do J1 and J2 generate under commutators?
     (full so(n)?  a proper subalgebra?)
  B. Phase-triviality theorem, checked: any operator whose hop phases are a
     function of DISPLACEMENT only (the cascade's i-per-step rule, phase
     i^(Delta d)) is gauge-equivalent to a real operator via U = diag(i^d);
     no composite of displacement-phased hops can ever carry flux.
  C. The loophole: T's signs are PARITY-dependent (evens shift up with +,
     odds shift down with +), i.e. position- not displacement-dependent.
     Combining the elastic chain (1-step, real) with the skew composite
     i(T - T^t) (2-step) closes triangles.  Measure the actual flux through
     every triangle; if nonzero, this is the first genuinely un-gaugeable
     cascade-native operator, and its level statistics get the same
     GUE/GOE/Poisson/crystal test as before.

Pre-registered priors: (A) full so(n); (B) triviality confirmed exactly;
(C) some nonzero staggered flux is possible, but the spectrum of a
deterministic quasi-1-D operator stays regular -- not GUE (0.5996).
"""

import math
from itertools import combinations

import numpy as np

D_MIN, D_MAX = 4, 217


def lnR(d):
    return math.lgamma((d + 1) / 2.0) - math.lgamma((d + 2) / 2.0)


def alpha(d):
    return math.exp(2.0 * lnR(d)) / 4.0


def N_lapse(d):
    return math.sqrt(math.pi) * math.exp(lnR(d))


def gap_ratio(e):
    s = np.diff(np.sort(e))
    s = s[s > 1e-12]
    r = np.minimum(s[1:], s[:-1]) / np.maximum(s[1:], s[:-1])
    return float(np.mean(r))


def spacing_cv(e):
    s = np.diff(np.sort(e))
    s = s[s > 1e-12]
    k = 9
    loc = np.array([np.mean(s[max(0, i - k // 2):i + k // 2 + 1])
                    for i in range(len(s))])
    u = s / loc
    return float(np.std(u) / np.mean(u))


def pairing_J(n, offset):
    J = np.zeros((n, n))
    k = offset
    while k + 1 < n:
        J[k + 1, k] = 1.0
        J[k, k + 1] = -1.0
        k += 2
    return J


