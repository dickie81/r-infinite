def part_C():
    print()
    print("=" * 78)
    print("PART C: chain + skew shift composite i(T - T^t)  (parity signs)")
    print("=" * 78)
    d = np.arange(D_MIN, D_MAX + 1)
    n = len(d)
    # T = J2 J1 restricted to the layer index chain
    J1, J2 = pairing_J(n, 0), pairing_J(n, 1)
    T = J2 @ J1
    w1 = np.array([1.0 / (2.0 * alpha(int(x))) for x in d[:-1]])
    w2 = np.array([N_lapse(int(x)) * N_lapse(int(x) + 1) for x in d[:-2]])
    H = np.zeros((n, n), dtype=complex)
    for j, w in enumerate(w1):
        H[j, j] += w
        H[j + 1, j + 1] += w
        H[j, j + 1] = -w
        H[j + 1, j] = -w
    S = (T - T.T) / 2.0
    for j in range(n - 2):
        c = 1j * w2[j] * S[j + 2, j]
        if abs(c) > 0:
            H[j + 2, j] += c
            H[j, j + 2] += np.conj(c)
    assert np.allclose(H, H.conj().T)
    # flux through every triangle (j, j+1, j+2)
    fluxes = []
    for j in range(n - 2):
        h1, h2, h3 = H[j + 1, j], H[j + 2, j + 1], H[j, j + 2]
        if abs(h1) > 0 and abs(h2) > 0 and abs(h3) > 0:
            fluxes.append(np.angle(h1 * h2 * h3))
    fluxes = np.array(fluxes)
    nz = np.abs(np.abs(fluxes) - math.pi / 2) < 1e-9
    print(f"  triangles: {len(fluxes)};  flux = +-pi/2 on {nz.sum()} of them"
          f"  (unique |flux| values: "
          f"{sorted(set(np.round(np.abs(fluxes)/math.pi, 3)))} pi)")
    # is it gauge-removable?  try the parity gauge U = diag(i^(d(d-1)/2))-ish:
    # generic test: real-equivalence iff there is a diagonal unitary making H
    # real; equivalently all cycle phases are 0 or pi.  Report directly:
    frustrated = np.abs(np.mod(np.abs(fluxes), math.pi)) > 1e-9
    print(f"  un-gaugeable (flux not in {{0, pi}}): {frustrated.sum()} triangles"
          f"  -> time-reversal genuinely {'BROKEN' if frustrated.any() else 'intact'}")
    e = np.linalg.eigvalsh(H)
    print(f"  spectrum: {n} levels;  <r~> = {gap_ratio(e):.4f}"
          f"   CV(unfolded) = {spacing_cv(e):.4f}")
    lo, hi = np.percentile(e, [10, 90])
    bulk = e[(e > lo) & (e < hi)]
    print(f"  bulk (10-90 pct): <r~> = {gap_ratio(bulk):.4f}"
          f"   CV = {spacing_cv(bulk):.4f}")
    print("  reference: Poisson 0.3863 | GOE 0.5307 | GUE 0.5996 | crystal ~1")
    return e


